                "сходить к стоматологу",
                "сделать отчёт по проекту",
                "смержить ветку и задеплоить",
                "закоммитить правки по интерфейсу",
                "записаться в зал",
                "разобрать почту",
                "просто заметка без ничего",
            )
        return cases.joinToString(separator = "\n") { text ->
            "${text} -> ${detect(text) ?: "нет"}"
        }
    }
