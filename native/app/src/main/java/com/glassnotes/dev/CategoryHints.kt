    /**
     * Категория по тексту заметки или `null`. Слова сравниваются по началу: «покуп» ловит
     * «покупки»/«покупать», а «код» не ловит «кодовый» случайно — это осознанный компромисс,
     * ошибки в сторону «без категории», а не в сторону чужой категории.
     */
    fun detect(text: String): String? {
        if (text.isBlank()) return null
        val lower = text.lowercase(Locale("ru")).replace('ё', 'е')
        val words = lower.split(Regex("[^\\p{L}\\p{N}-]+")).filter { it.isNotBlank() }

        val score = HashMap<String, Int>()
        for ((category, list) in rules) {
            for ((root, weight) in list) {
                if (hits(root, words, lower)) score[category] = (score[category] ?: 0) + weight
            }
        }

        val best = score.maxByOrNull { it.value }?.takeIf { it.value >= THRESHOLD } ?: return null
        // Равенство баллов решается порядком старшинства — предсказуемо и без «случайностей».
        val bestValue = best.value
        return ORDER.firstOrNull { (score[it] ?: -1) == bestValue } ?: best.key
    }

    private fun hits(
        root: String,
        words: List<String>,
        lower: String,
    ): Boolean =
        if (root.contains(' ')) {
            lower.contains(root)
        } else {
            words.any { it.startsWith(root) }
        }

    /** Таблица для проверки на телефоне: `--ez cat_test true`. */
