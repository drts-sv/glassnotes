package ru.gigapisar.audio

/**
 * Определитель речи: по кадру аудио отвечает, человек говорит или это шум.
 *
 * Интерфейс намеренно узкий: запись не должна знать, чем именно определяется речь.
 * Рабочая реализация — нейросетевой VAD (Silero) в `com.glassnotes.app.SileroVad`,
 * запасная — порог по громкости внутри самого рекордера.
 */
interface SpeechDetector {
    companion object {
        /** Кадр детектора при 16 кГц: 512 сэмплов = 32 мс (столько просит Silero). */
        const val FRAME_SAMPLES_16K = 512
    }

    /** Готов ли определитель (модель загрузилась). */
    val available: Boolean

    /** Вероятность речи 0..1 для кадра [FRAME_SAMPLES_16K] сэмплов. */
    fun probability(frame: FloatArray): Float

    /** Сброс состояния между фразами: иначе «речь» тянется из прошлой записи. */
    fun reset() {}

    /** Освободить ресурсы. */
    fun close() {}
}
